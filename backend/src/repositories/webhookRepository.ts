/**
 * @file webhookRepository.ts
 *
 * Data-access layer for user-registered outbound webhook endpoints.
 *
 * Business rules enforced here (not in the route handler):
 *   1. URLs must use HTTPS.
 *   2. Only one `meta`-kind webhook per channel (enforced in `create`).
 *   3. Secrets are stored AES-256-GCM encrypted; plaintext is never persisted.
 *   4. Ownership is checked on every read/update/delete via `teamId`.
 *
 * All mutations take an `encryptionKey` parameter so that the
 * `DATA_ENCRYPTION_KEY` binding never leaks into the repository layer — callers
 * (routes / services) pull it from the Worker environment and pass it in.
 */

import { db } from '../db/index.js';
import { userWebhooks, channels } from '../db/schema.js';
import { eq, and, count } from 'drizzle-orm';
import { ApiError } from '../utils/errors.js';
import { encrypt, decrypt } from '../utils/encryption.js';
import type { WebhookEventName } from '../types/webhook.types.js';

// ---------------------------------------------------------------------------
// Public-facing row shape
// ---------------------------------------------------------------------------

/** What callers receive from list/get operations. Secret is never exposed. */
export interface WebhookRow {
  id: number;
  teamId: number;
  channelId: number | null;
  kind: 'whatflow' | 'meta';
  url: string;
  /** Always `'***'` — the plaintext secret is never returned via the API. */
  secret: '***';
  events: WebhookEventName[];
  isActive: boolean;
  createdAt: Date;
  updatedAt: Date;
}

// ---------------------------------------------------------------------------
// Input shapes
// ---------------------------------------------------------------------------

export interface CreateWebhookInput {
  teamId: number;
  channelId?: number | null;
  kind: 'whatflow' | 'meta';
  url: string;
  /** Plaintext secret provided by the user (or auto-generated by the caller). */
  secret: string;
  events?: WebhookEventName[];
  isActive?: boolean;
}

export interface UpdateWebhookInput {
  url?: string;
  secret?: string;
  events?: WebhookEventName[];
  isActive?: boolean;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

/**
 * Validates that a URL is HTTPS and parseable.
 * @throws {ApiError} 422 if the URL is invalid or non-HTTPS.
 */
function assertHttpsUrl(url: string): void {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    throw new ApiError(422, 'Webhook URL is not a valid URL', 'INVALID_WEBHOOK_URL');
  }
  if (parsed.protocol !== 'https:') {
    throw new ApiError(422, 'Webhook URL must use HTTPS', 'INVALID_WEBHOOK_URL');
  }
}

/**
 * Parses the stored comma-separated events string back into a typed array.
 * Empty string → empty array (no events subscribed).
 */
function parseEvents(raw: string): WebhookEventName[] {
  if (!raw) return [];
  return raw.split(',').filter(Boolean) as WebhookEventName[];
}

/**
 * Serialises an array of event names to the stored comma-separated format.
 */
function serializeEvents(events: WebhookEventName[]): string {
  return events.join(',');
}

/**
 * Maps a raw DB row to the public WebhookRow shape.
 * Secret column is replaced with `'***'`.
 */
function toWebhookRow(row: typeof userWebhooks.$inferSelect): WebhookRow {
  return {
    id: row.id,
    teamId: row.teamId,
    channelId: row.channelId ?? null,
    kind: row.kind,
    url: row.url,
    secret: '***',
    events: parseEvents(row.events),
    isActive: row.isActive,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}

// ---------------------------------------------------------------------------
// Repository
// ---------------------------------------------------------------------------

export const webhookRepository = {
  /**
   * Creates a new webhook registration.
   *
   * Enforces:
   * - HTTPS URL
   * - Only one `meta`-kind webhook per channel
   * - `channelId` must belong to `teamId` (prevents cross-team registration)
   *
   * @param input      - Creation params including plaintext secret
   * @param hexKey     - `DATA_ENCRYPTION_KEY` from Worker bindings
   * @returns The created row (secret masked)
   */
  async create(input: CreateWebhookInput, hexKey: string): Promise<WebhookRow> {
    assertHttpsUrl(input.url);

    const {
      teamId,
      channelId = null,
      kind,
      url,
      secret,
      events = [],
      isActive = true,
    } = input;

    // Verify the channel belongs to the requesting team
    if (channelId !== null) {
      const [ch] = await db
        .select({ teamId: channels.teamId })
        .from(channels)
        .where(eq(channels.id, channelId))
        .limit(1);

      if (!ch) {
        throw new ApiError(404, 'Channel not found', 'NOT_FOUND');
      }
      if (ch.teamId !== teamId) {
        throw new ApiError(403, 'Channel does not belong to this team', 'FORBIDDEN');
      }

      // Enforce one meta webhook per channel
      if (kind === 'meta') {
        const [existing] = await db
          .select({ id: userWebhooks.id })
          .from(userWebhooks)
          .where(and(eq(userWebhooks.channelId, channelId), eq(userWebhooks.kind, 'meta')))
          .limit(1);

        if (existing) {
          throw new ApiError(
            409,
            'A meta webhook already exists for this channel. Delete it before creating a new one.',
            'META_WEBHOOK_EXISTS'
          );
        }
      }
    }

    const encryptedSecret = await encrypt(secret, hexKey);

    const [inserted] = await db
      .insert(userWebhooks)
      .values({
        teamId,
        channelId,
        kind,
        url,
        encryptedSecret,
        events: serializeEvents(events),
        isActive,
      })
      .returning();

    return toWebhookRow(inserted);
  },

  /**
   * Lists all webhooks for a team, ordered by newest first.
   * Secrets are never included in the output.
   *
   * @param teamId - The team whose webhooks to list
   * @param limit  - Max rows to return (default 50, hard-capped at 100)
   */
  async listByTeam(teamId: number, limit = 50): Promise<WebhookRow[]> {
    const cap = Math.min(limit, 100);
    const rows = await db
      .select()
      .from(userWebhooks)
      .where(eq(userWebhooks.teamId, teamId))
      .orderBy(userWebhooks.id)
      .limit(cap);

    return rows.map(toWebhookRow);
  },

  /**
   * Returns a single webhook by ID, enforcing team ownership.
   * @throws {ApiError} 404 if not found or not owned by the team
   */
  async getById(id: number, teamId: number): Promise<WebhookRow> {
    const [row] = await db
      .select()
      .from(userWebhooks)
      .where(and(eq(userWebhooks.id, id), eq(userWebhooks.teamId, teamId)))
      .limit(1);

    if (!row) {
      throw new ApiError(404, 'Webhook not found', 'NOT_FOUND');
    }

    return toWebhookRow(row);
  },

  /**
   * Returns all active webhooks registered for a specific channel.
   * Used at event dispatch time — returns the **decrypted** secret
   * so the caller can compute HMAC signatures.
   *
   * This is an internal method, not exposed via the REST API.
   *
   * @param channelId  - Channel to fetch webhooks for
   * @param hexKey     - `DATA_ENCRYPTION_KEY` from Worker bindings
   */
  async listActiveByChannel(
    channelId: number,
    hexKey: string
  ): Promise<Array<Omit<WebhookRow, 'secret'> & { secret: string }>> {
    const rows = await db
      .select()
      .from(userWebhooks)
      .where(and(eq(userWebhooks.channelId, channelId), eq(userWebhooks.isActive, true)));

    return Promise.all(
      rows.map(async (row) => ({
        ...toWebhookRow(row),
        secret: await decrypt(row.encryptedSecret, hexKey),
      }))
    );
  },

  /**
   * Partially updates a webhook. Only provided fields are changed.
   * If `secret` is included it is re-encrypted before storage.
   *
   * @throws {ApiError} 404 if not found or not owned by the team
   */
  async update(
    id: number,
    teamId: number,
    patch: UpdateWebhookInput,
    hexKey: string
  ): Promise<WebhookRow> {
    if (patch.url !== undefined) {
      assertHttpsUrl(patch.url);
    }

    const updates: Partial<typeof userWebhooks.$inferInsert> = {
      updatedAt: new Date(),
    };

    if (patch.url !== undefined) updates.url = patch.url;
    if (patch.events !== undefined) updates.events = serializeEvents(patch.events);
    if (patch.isActive !== undefined) updates.isActive = patch.isActive;
    if (patch.secret !== undefined) {
      updates.encryptedSecret = await encrypt(patch.secret, hexKey);
    }

    const [updated] = await db
      .update(userWebhooks)
      .set(updates)
      .where(and(eq(userWebhooks.id, id), eq(userWebhooks.teamId, teamId)))
      .returning();

    if (!updated) {
      throw new ApiError(404, 'Webhook not found', 'NOT_FOUND');
    }

    return toWebhookRow(updated);
  },

  /**
   * Hard-deletes a webhook, verifying team ownership first.
   * @throws {ApiError} 404 if not found or not owned by the team
   */
  async delete(id: number, teamId: number): Promise<void> {
    const [deleted] = await db
      .delete(userWebhooks)
      .where(and(eq(userWebhooks.id, id), eq(userWebhooks.teamId, teamId)))
      .returning({ id: userWebhooks.id });

    if (!deleted) {
      throw new ApiError(404, 'Webhook not found', 'NOT_FOUND');
    }
  },

  /**
   * Returns the total number of webhooks registered for a team.
   * Used for display / limit enforcement.
   */
  async countByTeam(teamId: number): Promise<number> {
    const [row] = await db
      .select({ total: count() })
      .from(userWebhooks)
      .where(eq(userWebhooks.teamId, teamId));

    return Number(row?.total ?? 0);
  },
};
